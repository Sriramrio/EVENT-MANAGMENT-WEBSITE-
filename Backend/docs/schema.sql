CREATE SCHEMA IF NOT EXISTS stall_booking;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Common enum-like checks use VARCHAR columns for EF compatibility and simple migrations.
CREATE TABLE stall_booking.tenants (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code varchar(40) NOT NULL UNIQUE,
  name varchar(150) NOT NULL,
  legal_name varchar(180) NOT NULL,
  gstin varchar(15),
  pan varchar(10),
  address varchar(500) NOT NULL,
  city varchar(100) NOT NULL,
  state varchar(100) NOT NULL,
  country varchar(100) NOT NULL DEFAULT 'India',
  pincode varchar(12) NOT NULL,
  email varchar(150) NOT NULL,
  phone varchar(30) NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid,
  updated_at timestamptz,
  updated_by uuid,
  deleted_at timestamptz,
  deleted_by uuid,
  is_deleted boolean NOT NULL DEFAULT false,
  correlation_id varchar(100),
  CONSTRAINT ck_tenants_gstin CHECK (gstin IS NULL OR gstin ~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$'),
  CONSTRAINT ck_tenants_pan CHECK (pan IS NULL OR pan ~ '^[A-Z]{5}[0-9]{4}[A-Z]$')
);

CREATE TABLE stall_booking.events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES stall_booking.tenants(id),
  event_code varchar(50) NOT NULL,
  event_name varchar(200) NOT NULL,
  venue_name varchar(200) NOT NULL,
  venue_address varchar(500),
  city varchar(100),
  district varchar(100),
  state varchar(100),
  country varchar(100) NOT NULL DEFAULT 'India',
  start_date date NOT NULL,
  end_date date NOT NULL,
  booking_open_date date NOT NULL,
  booking_close_date date NOT NULL,
  stall_block_validity_days int NOT NULL DEFAULT 3,
  default_gst_percentage numeric(5,2) NOT NULL DEFAULT 18.00,
  status varchar(40) NOT NULL DEFAULT 'Open',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid,
  updated_at timestamptz,
  updated_by uuid,
  deleted_at timestamptz,
  deleted_by uuid,
  is_deleted boolean NOT NULL DEFAULT false,
  correlation_id varchar(100),
  UNIQUE (tenant_id, event_code),
  CONSTRAINT ck_events_dates CHECK (end_date >= start_date AND booking_close_date >= booking_open_date),
  CONSTRAINT ck_events_status CHECK (status IN ('Draft','Open','Closed','Completed','Cancelled'))
);

CREATE TABLE stall_booking.stall_sizes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES stall_booking.tenants(id),
  event_id uuid NOT NULL REFERENCES stall_booking.events(id),
  code varchar(20) NOT NULL,
  display_name varchar(80) NOT NULL,
  width_m numeric(8,2) NOT NULL,
  depth_m numeric(8,2) NOT NULL,
  area_sq_m numeric(8,2) NOT NULL,
  base_amount numeric(14,2) NOT NULL,
  gst_percentage numeric(5,2) NOT NULL,
  total_amount numeric(14,2) NOT NULL,
  currency char(3) NOT NULL DEFAULT 'INR',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid,
  updated_at timestamptz,
  updated_by uuid,
  deleted_at timestamptz,
  deleted_by uuid,
  is_deleted boolean NOT NULL DEFAULT false,
  correlation_id varchar(100),
  UNIQUE (event_id, code),
  CONSTRAINT ck_stall_sizes_positive CHECK (width_m > 0 AND depth_m > 0 AND area_sq_m > 0 AND base_amount >= 0),
  CONSTRAINT ck_stall_sizes_total CHECK (total_amount = round(base_amount + (base_amount * gst_percentage / 100), 2))
);

CREATE TABLE stall_booking.stalls (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES stall_booking.tenants(id),
  event_id uuid NOT NULL REFERENCES stall_booking.events(id),
  stall_size_id uuid NOT NULL REFERENCES stall_booking.stall_sizes(id),
  stall_number varchar(40) NOT NULL,
  hall_name varchar(80),
  zone_name varchar(80),
  row_label varchar(40),
  floor_label varchar(40),
  layout_x int,
  layout_y int,
  current_status varchar(40) NOT NULL DEFAULT 'Available',
  current_booking_id uuid,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid,
  updated_at timestamptz,
  updated_by uuid,
  deleted_at timestamptz,
  deleted_by uuid,
  is_deleted boolean NOT NULL DEFAULT false,
  correlation_id varchar(100),
  UNIQUE (event_id, stall_number),
  CONSTRAINT ck_stalls_status CHECK (current_status IN ('Available','Blocked','Frozen','Released','Cancelled','Disabled'))
);

