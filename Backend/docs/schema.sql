CREATE TABLE stall_booking.stall_bookings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES stall_booking.tenants(id),
  event_id uuid NOT NULL REFERENCES stall_booking.events(id),
  exhibitor_id uuid NOT NULL REFERENCES stall_booking.exhibitors(id),
  billing_profile_id uuid NOT NULL REFERENCES stall_booking.billing_profiles(id),
  requested_stall_size_id uuid NOT NULL REFERENCES stall_booking.stall_sizes(id),
  allocated_stall_id uuid REFERENCES stall_booking.stalls(id),
  booking_registration_number varchar(40) NOT NULL UNIQUE,
  booking_date timestamptz NOT NULL DEFAULT now(),
  booking_status varchar(50) NOT NULL,
  fascia_name varchar(25) NOT NULL,
  display_notes varchar(500),
  electrical_requirement varchar(500),
  special_requirement varchar(500),
  hazardous_demo_declared boolean NOT NULL DEFAULT false,
  terms_accepted boolean NOT NULL,
  accuracy_accepted boolean NOT NULL,
  payment_timeline_accepted boolean NOT NULL,
  cancellation_policy_accepted boolean NOT NULL,
  privacy_consent_accepted boolean NOT NULL,
  declarant_name varchar(100) NOT NULL,
  declarant_designation varchar(100) NOT NULL,
  declaration_date date NOT NULL,
  block_expires_at timestamptz,
  last_email_sent_at timestamptz,
  confirmed_at timestamptz,
  cancelled_at timestamptz,
  cancellation_reason varchar(500),
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid,
  updated_at timestamptz,
  updated_by uuid,
  deleted_at timestamptz,
  deleted_by uuid,
  is_deleted boolean NOT NULL DEFAULT false,
  correlation_id varchar(100),
  CONSTRAINT ck_booking_status CHECK (booking_status IN ('Draft','Submitted','UnderReview','BlockedAwaitingPayment','PaymentSubmitted','PaymentVerified','PaymentRejected','Confirmed','ReleasedDueToNonPayment','Cancelled','Closed')),
  CONSTRAINT ck_booking_terms CHECK (terms_accepted AND accuracy_accepted AND payment_timeline_accepted AND cancellation_policy_accepted AND privacy_consent_accepted),
  CONSTRAINT ck_booking_block_expiry CHECK (booking_status <> 'BlockedAwaitingPayment' OR block_expires_at IS NOT NULL),
  CONSTRAINT ck_booking_confirmed_requires_stall CHECK (booking_status <> 'Confirmed' OR allocated_stall_id IS NOT NULL)
);

ALTER TABLE stall_booking.stalls
  ADD CONSTRAINT fk_stalls_current_booking FOREIGN KEY (current_booking_id) REFERENCES stall_booking.stall_bookings(id);

CREATE TABLE stall_booking.stall_allocations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES stall_booking.tenants(id),
  event_id uuid NOT NULL REFERENCES stall_booking.events(id),
  booking_id uuid NOT NULL REFERENCES stall_booking.stall_bookings(id),
  stall_id uuid NOT NULL REFERENCES stall_booking.stalls(id),
  allocation_status varchar(40) NOT NULL,
  blocked_at timestamptz NOT NULL,
  blocked_by uuid NOT NULL,
  block_expires_at timestamptz NOT NULL,
  frozen_at timestamptz,
  frozen_by uuid,
  released_at timestamptz,
  released_by uuid,
  release_reason varchar(500),
  previous_stall_id uuid REFERENCES stall_booking.stalls(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid,
  updated_at timestamptz,
  updated_by uuid,
  deleted_at timestamptz,
  deleted_by uuid,
  is_deleted boolean NOT NULL DEFAULT false,
  correlation_id varchar(100),
  CONSTRAINT ck_allocation_status CHECK (allocation_status IN ('Blocked','Frozen','Released','Cancelled','Changed')),
  CONSTRAINT ck_allocation_frozen CHECK (allocation_status <> 'Frozen' OR frozen_at IS NOT NULL),
  CONSTRAINT ck_allocation_release CHECK (allocation_status NOT IN ('Released','Cancelled') OR release_reason IS NOT NULL)
);

CREATE UNIQUE INDEX ux_active_allocation_per_booking ON stall_booking.stall_allocations(booking_id) WHERE allocation_status IN ('Blocked','Frozen') AND is_deleted = false;
CREATE UNIQUE INDEX ux_active_allocation_per_stall ON stall_booking.stall_allocations(stall_id) WHERE allocation_status IN ('Blocked','Frozen') AND is_deleted = false;

